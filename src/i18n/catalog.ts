export function message(locale: Locale, key: MessageKey, values: MessageValues = {}): string {
  return catalogs[locale][key].replace(/\{([A-Za-z][A-Za-z0-9]*)\}/gu, (placeholder, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : placeholder
  );
}

export function formatNumber(locale: Locale, value: number): string {
  return new Intl.NumberFormat(locale === 'ko' ? 'ko-KR' : 'en-US').format(value);
}

export function resolveLocale(
  storage: LocaleStorage | undefined,
  preferredLanguages: readonly string[]
): Locale {
  try {
    const stored = storage?.getItem(LOCALE_STORAGE_KEY);
    if (stored === 'en' || stored === 'ko') {
      return stored;
    }
  } catch {
    // Locale selection still falls back deterministically when storage is unavailable.
  }
  return preferredLanguages.some((language) => /^ko(?:-|$)/iu.test(language)) ? 'ko' : 'en';
}

export function persistLocale(storage: LocaleStorage | undefined, locale: Locale): boolean {
  try {
    storage?.setItem(LOCALE_STORAGE_KEY, locale);
    return storage !== undefined;
  } catch {
    return false;
  }
}

export function localizedError(locale: Locale, cause: unknown, fallback: MessageKey): string {
  const record = typeof cause === 'object' && cause !== null ? cause : undefined;
  const name = record && 'name' in record ? (record as { name?: unknown }).name : undefined;
  const code = record && 'code' in record ? (record as { code?: unknown }).code : undefined;
  const ruleId = record && 'ruleId' in record ? (record as { ruleId?: unknown }).ruleId : undefined;
  const namespace = name === 'PlanningError' ? 'planning' : name === 'PresetError' ? 'preset' : '';
  const identity =
    typeof code === 'string' ? (code.includes('.') ? code : `${namespace}.${code}`) : '';
  const key = errorKeys[identity] ?? fallback;
  return message(locale, key, {
    max:
      key === 'errorTooManyRules'
        ? MAX_RULES
        : key === 'errorRuleTextTooLong'
          ? formatNumber(locale, MAX_RULE_TEXT_BYTES)
          : key === 'errorInvalidSequencePadding'
            ? MAX_SEQUENCE_PADDING
            : key === 'errorTooManyOverrides'
              ? formatNumber(locale, MAX_OVERRIDES)
              : key === 'errorOverrideTextTooLong'
                ? formatNumber(locale, MAX_OVERRIDE_TEXT_BYTES)
                : key === 'errorPresetDocumentTooLarge'
                  ? formatNumber(locale, MAX_PRESET_DOCUMENT_BYTES)
                  : key === 'errorTooManyPresets'
                    ? MAX_PRESETS
                    : key === 'errorInvalidPresetName'
                      ? MAX_PRESET_NAME_BYTES
                      : '',
    rule: typeof ruleId === 'number' ? ruleId : '—',
  });
}
